import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createServer } from "vite";
import { chromium } from "playwright";

const ui = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const server = await createServer({ root: ui, server: { host: "127.0.0.1", port: 0 } });
let browser;
try {
  await server.listen();
  browser = await chromium.launch({ channel: process.env.CLEO_TEST_BROWSER || "chrome", headless: true });
  const page = await browser.newPage();
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto(`${server.resolvedUrls.local[0]}scripts/fixtures/release-selection.html`);
  await page.getByRole("status", { name: "仓库发布权限" }).waitFor();
  assert.match(await page.getByRole("status", { name: "仓库发布权限" }).innerText(), /fixture-owner.*owner/);
  await page.getByRole("button", { name: "核对发布提交" }).click();
  await page.getByLabel("版本标签", { exact: true }).fill("v0.8.0-beta.1");
  await page.getByLabel("发布标题", { exact: true }).fill("Preview release");
  await page.getByLabel("发布类型", { exact: true }).selectOption("pre");
  await page.getByRole("button", { name: "确认创建 Release" }).click();
  await page.getByRole("link", { name: "查看 GitHub Release" }).waitFor();
  assert.equal(await page.getByRole("link", { name: "查看 PR", exact: true }).getAttribute("href"), "https://github.com/StDoses72/Cleo-AI-agent/pull/42");
  const calls = JSON.parse(await page.getByTestId("calls").textContent());
  assert.equal(calls.at(-1).params.prerelease, true);
  assert.equal(calls.at(-1).params.commit, "a".repeat(40));
  await page.getByLabel("目标更新版本").selectOption("v0.8.0-beta.1");
  assert.equal(await page.getByLabel("目标更新版本").inputValue(), "v0.8.0-beta.1");
  await page.getByLabel("目标更新版本").selectOption("v0.3.0");
  assert.equal(await page.getByLabel("目标更新版本").inputValue(), "v0.3.0");
  const unavailable = await page.locator('option[value="v0.1.0"]').evaluate(option => ({ html: option.outerHTML, disabled: option.disabled }));
  assert.equal(unavailable.disabled, true, unavailable.html);
  const output = join(ui, "output/playwright/releases");
  await mkdir(output, { recursive: true });
  for (const width of [1280, 390]) {
    await page.setViewportSize({ width, height: 900 });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Layout overflows at ${width}px`);
    await page.screenshot({ path: join(output, `release-${width}.png`), fullPage: true });
  }
  await page.reload();
  await page.getByRole("button", { name: "核对发布提交" }).click();
  await page.getByLabel("版本标签", { exact: true }).fill("v0.8.0");
  await page.getByLabel("发布标题", { exact: true }).fill("Stable release");
  await page.getByLabel("发布类型", { exact: true }).selectOption("stable");
  await page.getByRole("button", { name: "确认创建 Release" }).click();
  await page.getByRole("link", { name: "查看 GitHub Release" }).waitFor();
  const stableCalls = JSON.parse(await page.getByTestId("calls").textContent());
  assert.equal(stableCalls.at(-1).params.prerelease, false);
  await page.reload();
  await page.getByRole("button", { name: "核对发布提交" }).click();
  await page.getByLabel("版本标签", { exact: true }).fill("v0.9.0");
  await page.getByLabel("发布标题", { exact: true }).fill("Next release");
  assert.equal(await page.getByRole("button", { name: "确认创建 Release" }).isEnabled(), true);
  await page.getByRole("button", { name: "撤销权限（测试）" }).click();
  assert.equal(await page.getByRole("button", { name: "核对发布提交" }).isDisabled(), true);
  assert.equal(await page.getByRole("button", { name: "确认创建 Release" }).isDisabled(), true);
  assert.equal(await page.getByRole("button", { name: "继续提交 PR", exact: true }).isEnabled(), true);
  assert.deepEqual(errors, []);
  console.log("PASS: permission display/revocation, release payload and links, prerelease/history selection, platform gate, desktop/mobile layout");
} finally { await browser?.close(); await server.close(); }
